import assert from 'node:assert/strict';
import { defaultARFit, fitKey, readARFit, saveARFit } from './arFit.ts';

const values = new Map();
const storage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
const red = '/models/red.glb';
const blue = '/models/blue.glb';
saveARFit(red, { ...defaultARFit, headWidth: 108, headHeight: 93, scale: 112, skullDepth: -7 }, storage);
assert.equal(readARFit(red, storage).headWidth, 108);
assert.equal(readARFit(red, storage).headHeight, 93);
assert.equal(readARFit(red, storage).scale, 112);
assert.deepEqual(readARFit(blue, storage), defaultARFit, 'models have separate calibration');
values.set(fitKey(red), '{bad json');
assert.deepEqual(readARFit(red, storage), defaultARFit, 'corrupt storage falls back safely');
values.set(fitKey(red), JSON.stringify({ pd: Infinity, scale: 900, headWidth: -20, headHeight: 'huge', depth: null }));
const sanitized = readARFit(red, storage);
assert.equal(sanitized.pd, 63);
assert.equal(sanitized.scale, 135);
assert.equal(sanitized.headWidth, 80);
assert.equal(sanitized.headHeight, 100);
assert.equal(sanitized.depth, 0);
assert.doesNotThrow(() => saveARFit(red, defaultARFit, { setItem: () => { throw new Error('storage disabled'); } }));
const previousStorage = Object.getOwnPropertyDescriptor(globalThis, 'localStorage');
Object.defineProperty(globalThis, 'localStorage', { configurable: true, get() { throw new Error('storage access denied'); } });
assert.deepEqual(readARFit(red), defaultARFit, 'blocked storage getter falls back safely');
assert.doesNotThrow(() => saveARFit(red, defaultARFit), 'blocked storage getter does not interrupt calibration');
if (previousStorage) Object.defineProperty(globalThis, 'localStorage', previousStorage);
else delete globalThis.localStorage;
console.log('Per-model calibration, corrupt values, bounds, and unavailable storage checks passed.');
