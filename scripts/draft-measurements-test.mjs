import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import ts from 'typescript';
const source=await fs.readFile('frontend/src/draftMeasurements.ts','utf8');
const compiled=ts.transpile(source,{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022});
const {approximateMeasurements,measurementIssue}=await import('data:text/javascript;base64,'+Buffer.from(compiled).toString('base64'));
for(const depth of [.2,17,NaN,Infinity])assert.match(measurementIssue({frame_thickness:{value:depth,source:'manual'}}),/0.8–16 mm/);
for(const depth of [.8,2,4,16])assert.equal(measurementIssue({frame_thickness:{value:depth,source:'inferred'}}),null);
assert.equal(measurementIssue({}),null,'Missing depth stays explicitly optional, not a fabricated measurement');
const rect=(part,x,y,w,h)=>({part,points:[{x,y},{x:x+w,y:y+h}]});
const a=[rect('front',0,0,1000,400),rect('lens-left',60,30,370,300),rect('lens-right',570,30,370,300)];
const values=approximateMeasurements(a,{});
assert.deepEqual(values.frame_width,{value:140,source:'default'});
assert.deepEqual(values.temple_length,{value:140,source:'default'});
assert.deepEqual(values.lens_width,{value:51.8,source:'inferred'});
assert.deepEqual(values.lens_height,{value:42,source:'inferred'});
assert.deepEqual(values.bridge_width,{value:19.6,source:'inferred'});
const existing={frame_width:{value:130,source:'published'},temple_length:{value:145,source:'measured'}};
const supplied=approximateMeasurements(a,existing);
assert.deepEqual(supplied.frame_width,existing.frame_width);
assert.deepEqual(supplied.temple_length,existing.temple_length);
assert.equal(Object.keys(existing).length,2);
const bad={frame_width:{value:.2,source:'manual'},lens_width:{value:.08,source:'inferred'},lens_height:{value:.06,source:'inferred'},bridge_width:{value:1,source:'inferred'},temple_length:{value:140,source:'default'}};
assert.match(measurementIssue(bad),/millimeters, not meters/);
assert.throws(()=>approximateMeasurements(a,bad),/millimeters, not meters/);
const recovered=approximateMeasurements(a,bad,true);
assert.deepEqual(recovered,values);
assert.equal(bad.frame_width.value,.2,'Recovery must not mutate saved input before approval');
const scaled=approximateMeasurements(a,{...values,frame_width:{value:160,source:'manual'}});
assert.equal(scaled.lens_width.value,59.2,'Inferred dimensions must track a changed scale');
assert.equal(scaled.bridge_width.value,22.4);
assert.equal(measurementIssue(scaled),null);
console.log('Approximate dimension checks passed.');
