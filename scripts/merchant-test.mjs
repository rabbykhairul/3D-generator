import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const base='http://127.0.0.1:5188';
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
 const p=await (await page.request.post(base+'/api/samples/synthetic-opaque-full-rim/import')).json();
 await page.request.patch(base+'/api/projects/'+p.id,{data:{name:'Merchant flow QA',annotations:[],measurements:{}}});
 await page.goto(base);
 await page.getByRole('heading',{name:'Merchant flow QA',exact:true}).waitFor();
 assert.equal(await page.locator('.capture-slot').count(),5);
 assert.equal(await page.getByText('Needed',{exact:true}).count(),0);
 await page.getByRole('button',{name:/Generate model/}).first().click();
 await page.getByRole('img',{name:'Detected outlines on current front photo'}).waitFor();
 assert.equal(await page.getByRole('button',{name:'Approve outlines & generate draft',exact:true}).isDisabled(),true);
 await page.getByRole('checkbox',{name:/Use approximate size/}).check();
 await page.getByRole('button',{name:'Approve outlines & generate draft',exact:true}).click();
 await page.getByText('Model generated',{exact:true}).waitFor({timeout:30000});
 await page.getByLabel('Interactive three-dimensional eyewear model').waitFor();
 const first=await (await page.request.get(base+'/api/projects/'+p.id)).json();
 assert.equal(first.artifact.metadata.provenance.front.photo_id,p.photos[0].id);
 assert.equal(first.measurements.frame_width.source,'default');
 assert.ok(first.artifact.metadata.warnings.some(w=>w.includes('Approximate-size draft')));
 await page.getByRole('tab',{name:/Photos/}).click();
 await page.getByRole('button',{name:'Advanced: extra views & validation'}).click();
 assert.equal(await page.locator('.capture-slot').count(),13);
 await page.getByRole('button',{name:'Hide advanced capture'}).click();
 // A blank replacement must not leave the old preview or old approval usable.
 const blank=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=600;c.height=300;const x=c.getContext('2d');x.fillStyle='white';x.fillRect(0,0,600,300);return c.toDataURL().split(',')[1];});
 const chooser=page.waitForEvent('filechooser');
 await page.getByRole('button',{name:'Upload newer photo'}).first().click();
 await (await chooser).setFiles({name:'blank-replacement.png',mimeType:'image/png',buffer:Buffer.from(blank,'base64')});
 await page.getByText('Model out of date',{exact:true}).waitFor();
 await page.getByRole('tab',{name:/Review \/ AR/}).click();
 await page.getByRole('heading',{name:'Your photos or settings changed'}).waitFor();
 assert.equal(await page.getByLabel('Interactive three-dimensional eyewear model').count(),0);
 await page.getByRole('button',{name:'Prepare draft from photos →'}).click();
 await page.getByRole('button',{name:'Analyze current front photo'}).click();
 await page.getByText(/We could not identify all required boundaries/).waitFor();
 assert.equal(await page.getByRole('button',{name:'Approve outlines & generate draft'}).isDisabled(),true);
 await page.screenshot({path:'artifacts/qa-merchant-flow.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2),false);
 assert.deepEqual(errors,[]);
 await fs.writeFile('artifacts/merchant-results.json',JSON.stringify({passed:true,checks:['three-photo default','advanced optional capture','actual automatic contour extraction','one-click approval and CPU draft generation','front photo provenance','replacement invalidates old preview','failed analysis cannot generate generic frame','mobile layout'],errors},null,2));
 console.log('Merchant workflow checks passed.');
}finally{await browser.close();}
